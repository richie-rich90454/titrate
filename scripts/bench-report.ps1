<#
.SYNOPSIS
    Aggregate Criterion estimates.json files into a Markdown table with
    environment metadata.

.DESCRIPTION
    Reads only Criterion `new/estimates.json` files that pass the -Since,
    -Group and -Benchmark filters. Missing results are never inferred, and no
    timing value is generated by this script. Losses are computed relative to
    the first benchmark in each group whose name matches -BaselineToken.
    Results are printed to stdout; -OutFile also writes the Markdown.

.PARAMETER CriterionDir
    Directory containing Criterion output (default: target/criterion).

.PARAMETER OutFile
    Optional path to write the Markdown report to.

.PARAMETER Since
    Include only estimates written at or after this time (default: 24 hours).

.PARAMETER Group
    Wildcard filter for the Criterion group directory name.

.PARAMETER Benchmark
    Wildcard filter for the benchmark directory name.

.PARAMETER Profile
    Build profile label recorded in the environment section.

.PARAMETER BaselineToken
    Substring identifying the baseline benchmark within each group.

.EXAMPLE
    .\scripts\bench-report.ps1
    .\scripts\bench-report.ps1 -Since (Get-Date).AddMinutes(-30) -Group native_vs_rust
    .\scripts\bench-report.ps1 -OutFile .\bench-report.md -Profile release
#>
[CmdletBinding()]
param(
    [string]$CriterionDir = (Join-Path $PSScriptRoot '..\target\criterion'),
    [string]$OutFile,
    [datetime]$Since = (Get-Date).AddDays(-1),
    [string]$Group = '*',
    [string]$Benchmark = '*',
    [string]$Profile = 'unspecified',
    [string]$BaselineToken = 'rust'
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot

if (-not [System.IO.Path]::IsPathRooted($CriterionDir)) {
    $CriterionDir = Join-Path $root $CriterionDir
}
if (-not (Test-Path -LiteralPath $CriterionDir)) {
    throw "Criterion directory not found: $CriterionDir"
}
$criterionDir = (Resolve-Path -LiteralPath $CriterionDir).Path

function Convert-ToNs($Estimate) {
    if ($null -eq $Estimate) { return $null }
    $raw = $Estimate.estimate
    if ($null -eq $raw) { $raw = $Estimate.mean }
    if ($null -eq $raw) { return $null }

    $value = 0.0
    if (-not [double]::TryParse([string]$raw, [ref]$value)) { return $null }

    $unit = [string]$Estimate.unit
    if ([string]::IsNullOrWhiteSpace($unit)) { $unit = 'ns' }
    switch ($unit) {
        'ns' { return $value }
        'us' { return $value * 1000.0 }
        'ms' { return $value * 1000000.0 }
        's'  { return $value * 1000000000.0 }
        default { return $value }
    }
}

function Format-Loss($MeanNs, $BaselineNs) {
    if ($null -eq $MeanNs -or $null -eq $BaselineNs -or $BaselineNs -le 0) {
        return 'not measured'
    }
    $ratio = $MeanNs / $BaselineNs
    return ('{0:F2}x ({1:F1}%)' -f $ratio, (($ratio - 1.0) * 100.0))
}

function Get-VersionText([string]$Name) {
    if ($null -eq (Get-Command $Name -ErrorAction SilentlyContinue)) {
        return "$Name unavailable"
    }
    try {
        $line = & $Name --version 2>$null | Select-Object -First 1
    }
    catch {
        return "$Name unavailable"
    }
    if ([string]::IsNullOrWhiteSpace([string]$line)) { return "$Name unavailable" }
    return [string]$line
}

$rows = @()
foreach ($file in (Get-ChildItem -LiteralPath $criterionDir -Recurse -Filter 'estimates.json' -File)) {
    # Criterion keeps a stale `base/` alongside the current `new/` result.
    if ($file.Directory.Name -ne 'new') { continue }
    if ($file.LastWriteTime -lt $Since) { continue }

    $benchmarkName = $file.Directory.Parent.Name
    $groupName = $file.Directory.Parent.Parent.Name
    if ($groupName -notlike $Group -or $benchmarkName -notlike $Benchmark) { continue }

    $json = Get-Content -LiteralPath $file.FullName -Raw | ConvertFrom-Json
    $meanNs = Convert-ToNs $json.mean
    if ($null -eq $meanNs) { continue }

    $rows += [pscustomobject]@{
        Group       = $groupName
        Benchmark   = $benchmarkName
        MeanNs      = $meanNs
        StdDevNs    = Convert-ToNs $json.std_dev
        MeasuredAt  = $file.LastWriteTime.ToString('s')
    }
}
$rows = @($rows | Sort-Object Group, Benchmark)

$baselineByGroup = @{}
if (-not [string]::IsNullOrWhiteSpace($BaselineToken)) {
    foreach ($row in $rows) {
        if ($row.Benchmark -like "*$BaselineToken*" -and -not $baselineByGroup.ContainsKey($row.Group)) {
            $baselineByGroup[$row.Group] = $row.MeanNs
        }
    }
}

$gitCommand = Get-Command git -ErrorAction SilentlyContinue
$commit = 'git unavailable'
if ($null -ne $gitCommand) {
    $commit = (& git rev-parse HEAD 2>$null | Select-Object -First 1)
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace([string]$commit)) {
        $commit = 'git unavailable'
    }
}

$cpu = $env:PROCESSOR_IDENTIFIER
if ([string]::IsNullOrWhiteSpace($cpu)) {
    try { $cpu = (Get-CimInstance Win32_Processor | Select-Object -First 1).Name } catch { $cpu = 'unknown' }
}
if ([string]::IsNullOrWhiteSpace([string]$cpu)) { $cpu = 'unknown' }

$ram = 'unknown'
try {
    $bytes = (Get-CimInstance Win32_ComputerSystem).TotalPhysicalMemory
    if ($null -ne $bytes -and $bytes -gt 0) {
        $ram = ('{0:F1} GiB' -f ($bytes / 1GB))
    }
}
catch {
    $ram = 'unknown'
}

$envRows = @(
    [pscustomobject]@{ Field = 'Generated (UTC)'; Value = (Get-Date).ToUniversalTime().ToString('o') },
    [pscustomobject]@{ Field = 'Commit'; Value = [string]$commit },
    [pscustomobject]@{ Field = 'rustc'; Value = (Get-VersionText 'rustc') },
    [pscustomobject]@{ Field = 'cargo'; Value = (Get-VersionText 'cargo') },
    [pscustomobject]@{ Field = 'OS'; Value = [System.Environment]::OSVersion.VersionString },
    [pscustomobject]@{ Field = 'CPU'; Value = $cpu },
    [pscustomobject]@{ Field = 'RAM'; Value = $ram },
    [pscustomobject]@{ Field = 'Profile'; Value = $Profile },
    [pscustomobject]@{ Field = 'Criterion directory'; Value = $criterionDir },
    [pscustomobject]@{ Field = 'Included since'; Value = $Since.ToString('s') },
    [pscustomobject]@{ Field = 'Group filter'; Value = $Group },
    [pscustomobject]@{ Field = 'Benchmark filter'; Value = $Benchmark }
)

$lines = New-Object System.Collections.Generic.List[string]
[void]$lines.Add('# Benchmark report')
[void]$lines.Add('')
[void]$lines.Add('## Environment (record this with any published number)')
[void]$lines.Add('')
[void]$lines.Add('| Field | Value |')
[void]$lines.Add('|---|---|')
foreach ($row in $envRows) {
    [void]$lines.Add(('| {0} | {1} |' -f $row.Field, $row.Value))
}
[void]$lines.Add('')
[void]$lines.Add('## Results')
[void]$lines.Add('')
if ($rows.Count -eq 0) {
    [void]$lines.Add('_No Criterion results matched the filters._')
}
else {
    [void]$lines.Add('| Group | Benchmark | Mean (ns/iter) | Std dev (ns) | vs baseline | Measured at |')
    [void]$lines.Add('|---|---|---:|---:|---:|---|')
    foreach ($row in $rows) {
        $baseline = $null
        if ($baselineByGroup.ContainsKey($row.Group)) { $baseline = $baselineByGroup[$row.Group] }
        $deviation = if ($null -eq $row.StdDevNs) { '-' } else { $row.StdDevNs.ToString('F2') }
        [void]$lines.Add(('| {0} | {1} | {2:F2} | {3} | {4} | {5} |' -f
            $row.Group, $row.Benchmark, $row.MeanNs, $deviation,
            (Format-Loss $row.MeanNs $baseline), $row.MeasuredAt))
    }
}
[void]$lines.Add('')
[void]$lines.Add('Loss = mean / baseline - 1, with the baseline chosen by -BaselineToken.')
[void]$lines.Add('Every row comes from a Criterion `new/estimates.json` file; missing results are not inferred.')

$report = $lines -join [Environment]::NewLine
if (-not [string]::IsNullOrWhiteSpace($OutFile)) {
    Set-Content -LiteralPath $OutFile -Value $report -Encoding utf8
}
Write-Output $report
